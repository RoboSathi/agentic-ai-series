@pytest.mark.parametrize(
    ("stage", "status", "fields", "summary", "detail", "kind", "expected"), CASES
)
def test_the_summary_line(
    stage: str,
    status: StatusKind,
    fields: dict[str, Any],
    summary: str | None,
    detail: str | None,
    kind: EventKind,
    expected: str,
) -> None:
    event = StatusEvent(
        stage=stage, status=status, fields=fields, summary=summary, detail=detail, event_kind=kind
    )
    assert summarise(event, StageLabelRegistry()) == expected


def test_every_stage_with_a_writer_is_covered_above() -> None:
    assert set(SUMMARISERS) <= {case[0] for case in CASES}
