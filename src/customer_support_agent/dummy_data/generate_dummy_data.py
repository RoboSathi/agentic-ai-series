"""`make dummy-data`: rebuild the demo database and everything derived from it.

Generates seed_data.sql from `generator.yaml` (deterministic: a fixed
random seed) and rebuilds agentic.db from schema.sql + seed_data.sql +
this agent's runtime policy. Then, because regenerated orders make any
state that remembers the old ones stale, it resets the checkpoint file
and the episodic logs (`--keep-memory` keeps them), and rebuilds the
eval fixture with the same builder `make eval-generate` uses.

The eval history (`data/evals.duckdb`) and observability analytics are
never touched: a data reset is not a reason to lose trend lines.

The data obeys the domain's own rules. Generating each column
independently is easy and wrong: it produced pending orders with
completed refunds, which is a state the business cannot reach, and an
agent asked to reason over impossible data will produce impossible
answers and look like a model problem.
"""

import argparse
import random
import shutil
from collections.abc import Sequence
from datetime import datetime, timedelta, timezone
from functools import cache
from pathlib import Path

import yaml
from pydantic import BaseModel

from agentic_commons.config import get_settings
from agentic_commons.logging import get_logger
from agentic_commons.persistence import SqliteConnectionPool, SqlitePlatformStore
from agentic_commons.security.auth.policy import AgentPolicyRepository
from customer_support_agent.config import get_agent_settings
from customer_support_agent.domain.models import REFUNDABLE_ORDER_STATUSES
from customer_support_agent.dummy_data import DUMMY_DATA_DIR
from customer_support_agent.evals.fixture import EvalFixture, policy_seed_sql

# The DDL lives with the persistence layer that owns it, not with the
# fixture data that happens to be loaded into it.
_SCHEMA_FILE = DUMMY_DATA_DIR.parent / "persistence" / "schema.sql"
_SEED_DATA_FILE = DUMMY_DATA_DIR / "seed_data.sql"
_HEADER = "-- Generated by generate_dummy_data.py — do not hand-edit."

_logger = get_logger("persistence")


class CatalogueItem(BaseModel):
    name: str
    sku: str
    low: float
    high: float


class GeneratorSpec(BaseModel):
    """Everything `generator.yaml` declares about the synthetic shop."""

    random_seed: int
    users: int
    orders: int
    first_user_id: int
    first_order_id: int
    currency: str
    user_code_digits: str
    user_created_days_ago: tuple[int, int]
    order_placed_days_ago: tuple[int, int]
    email_template: str
    phone_prefix: str
    phone_digits: tuple[int, int]
    order_status_weights: dict[str, float]
    refund_status_weights: dict[str, float]
    in_flight_refund_status: str
    quantity_weights: dict[int, float]
    pending_eta_days: tuple[int, int]
    delivered_after_days: tuple[int, int]
    shipped_eta_days: tuple[int, int]
    tracking_suffix: str
    tracking_digits: tuple[int, int]
    first_names: list[str]
    last_names: list[str]
    catalogue: list[CatalogueItem]
    carriers: list[str]
    transit_locations: list[str]


@cache
def generator_spec() -> GeneratorSpec:
    """The generator's declaration, read once."""
    path = get_agent_settings().resolved_dummy_data_generator_path
    return GeneratorSpec.model_validate(yaml.safe_load(path.read_text()))


def refund_status_for(rng: random.Random, order_status: str) -> str:
    """The refund status an order in this state is allowed to have.

    An order becomes refundable only once it is settled — delivered, or
    cancelled before delivery. A pending or shipped order is still in
    flight, so it can only carry the no-refund status.
    """
    spec = generator_spec()
    if order_status not in REFUNDABLE_ORDER_STATUSES:
        return spec.in_flight_refund_status
    return _weighted_choice(rng, spec.refund_status_weights)


def _user_code(rng: random.Random, taken: set[str]) -> str:
    """A unique code, unambiguous and never a plain word (one digit at least)."""
    settings, digits = get_agent_settings(), generator_spec().user_code_digits
    length = settings.user_code_length
    while True:
        body = rng.choices(settings.user_code_alphabet, k=length - 1)
        body.insert(rng.randrange(length), rng.choice(digits))
        code = "".join(body)
        if code not in taken and any(char.isdigit() for char in code):
            taken.add(code)
            return code


def _whereabouts(
    rng: random.Random, order_status: str, timestamp: str, now: datetime
) -> tuple[str | None, str | None, str | None, str | None, str | None]:
    """Carrier, tracking, ETA, delivered_at and location for this status.

    The rule the agent applies is the rule the fixtures obey: a cancelled
    order has no delivery date, a pending one is in no depot.
    """
    spec = generator_spec()
    placed = datetime.fromisoformat(timestamp)
    if order_status == "pending":
        eta = (placed + timedelta(days=rng.randint(*spec.pending_eta_days))).isoformat()
        return None, None, eta, None, None
    if order_status == "cancelled":
        return None, None, None, None, None
    carrier = rng.choice(spec.carriers)
    tracking = f"{carrier[:2].upper()}{rng.randint(*spec.tracking_digits)}{spec.tracking_suffix}"
    if order_status == "delivered":
        delivered = placed + timedelta(days=rng.randint(*spec.delivered_after_days))
        delivered = min(delivered, now)
        return carrier, tracking, delivered.isoformat(), delivered.isoformat(), None
    eta = (placed + timedelta(days=rng.randint(*spec.shipped_eta_days))).isoformat()
    return carrier, tracking, eta, None, rng.choice(spec.transit_locations)


def _sql_null(value: str | None) -> str:
    """Inline SQL for an optional text column."""
    return _sql_str(value) if value is not None else "NULL"


def _sql_str(value: str) -> str:
    """Quote and escape a string for inline SQL."""
    return "'" + value.replace("'", "''") + "'"


def _weighted_choice(rng: random.Random, weights: dict[str, float]) -> str:
    return rng.choices(list(weights), weights=list(weights.values()), k=1)[0]


def _user_lines(rng: random.Random, now: datetime, spec: GeneratorSpec) -> list[str]:
    lines = ["-- Users"]
    taken: set[str] = set()
    for index, user_id in enumerate(_user_ids(spec), start=1):
        created_at = (now - timedelta(days=rng.randint(*spec.user_created_days_ago))).isoformat()
        name = f"{rng.choice(spec.first_names)} {rng.choice(spec.last_names)}"
        email = spec.email_template.format(index=index)
        phone = f"{spec.phone_prefix}{rng.randint(*spec.phone_digits)}"
        lines.append(
            "INSERT INTO users (user_id, user_code, created_at, name, email, phone) VALUES "
            f"({user_id}, {_sql_str(_user_code(rng, taken))}, {_sql_str(created_at)}, "
            f"{_sql_str(name)}, {_sql_str(email)}, {_sql_str(phone)});"
        )
    return lines


def _order_line(rng: random.Random, now: datetime, spec: GeneratorSpec, order_id: int) -> str:
    user_id = rng.choice(_user_ids(spec))
    timestamp = (now - timedelta(days=rng.randint(*spec.order_placed_days_ago))).isoformat()
    order_status = _weighted_choice(rng, spec.order_status_weights)
    refund_status = refund_status_for(rng, order_status)
    item = rng.choice(spec.catalogue)
    quantity = rng.choices(
        list(spec.quantity_weights), weights=list(spec.quantity_weights.values()), k=1
    )[0]
    # Integer cents throughout: a price drawn in cents, a total that is an
    # exact product — no float ever becomes money.
    per_major = 10 ** get_settings().money.minor_units
    unit_price_cents = rng.randint(round(item.low * per_major), round(item.high * per_major))
    amount_cents = unit_price_cents * quantity
    carrier, tracking, eta, delivered_at, location = _whereabouts(rng, order_status, timestamp, now)
    return (
        "INSERT INTO orders "
        "(order_id, user_id, timestamp, order_status, refund_status, amount_cents, "
        "product_name, product_sku, quantity, unit_price_cents, currency, "
        "carrier, tracking_number, estimated_delivery_date, delivered_at, current_location) "
        f"VALUES ({order_id}, {user_id}, {_sql_str(timestamp)}, {_sql_str(order_status)}, "
        f"{_sql_str(refund_status)}, {amount_cents}, {_sql_str(item.name)}, {_sql_str(item.sku)}, "
        f"{quantity}, {unit_price_cents}, {_sql_str(spec.currency)}, {_sql_null(carrier)}, "
        f"{_sql_null(tracking)}, {_sql_null(eta)}, {_sql_null(delivered_at)}, "
        f"{_sql_null(location)});"
    )


def _user_ids(spec: GeneratorSpec) -> list[int]:
    return list(range(spec.first_user_id, spec.first_user_id + spec.users))


def generate_seed_sql() -> str:
    """seed_data.sql's content: INSERTs for every user and order."""
    spec = generator_spec()
    rng = random.Random(spec.random_seed)
    now = datetime.now(timezone.utc)
    lines = [_HEADER, "", *_user_lines(rng, now, spec), "", "-- Orders"]
    lines += [
        _order_line(rng, now, spec, spec.first_order_id + offset) for offset in range(spec.orders)
    ]
    return "\n".join(lines) + "\n"


def build_agent_database(seed_sql: str) -> Path:
    """Rebuild agentic.db from schema, seed and policy; report the policy it now holds."""
    db_path = get_agent_settings().resolved_db_path
    db_path.unlink(missing_ok=True)
    pool = SqliteConnectionPool(db_path)
    try:
        pool.execute_script(_SCHEMA_FILE.read_text())
        pool.execute_script(seed_sql)
        pool.execute_script(policy_seed_sql())
        _log_policy(pool)
    finally:
        pool.close()
    return db_path


def _log_policy(pool: SqliteConnectionPool) -> None:
    """What the database now grants — read back, not restated from the seed."""
    agent_id = get_settings().agent.id
    policy = AgentPolicyRepository(SqlitePlatformStore(pool, agent_id=agent_id)).get()
    _logger.info(
        "Applied agent runtime policy",
        agent=policy.agent_id,
        role=policy.role,
        authority_rank=policy.authority_rank,
        permissions=sorted(policy.permissions),
        limits={
            name: {
                "per_action": str(limit.per_action),
                "window": str(limit.window),
                "window_hours": limit.window_hours,
            }
            for name, limit in policy.limits.items()
        },
    )


def reset_derived_state() -> list[Path]:
    """Checkpoints and episodic logs remember the old orders; remove them."""
    removed = []
    checkpoints = get_settings().durability.resolved_db_path
    if checkpoints.exists():
        checkpoints.unlink()
        removed.append(checkpoints)
    episodic = get_settings().memory.episodic.resolved_path
    if episodic.exists():
        shutil.rmtree(episodic)
        removed.append(episodic)
    return removed


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument(
        "--keep-memory", action="store_true", help="keep checkpoints and episodic logs"
    )
    args = parser.parse_args(argv)

    spec = generator_spec()
    seed_sql = generate_seed_sql()
    _SEED_DATA_FILE.write_text(seed_sql)
    db_path = build_agent_database(seed_sql)
    _logger.info(
        f"Built {db_path}",
        users=spec.users,
        orders=spec.orders,
        order_ids=f"{spec.first_order_id}-{spec.first_order_id + spec.orders - 1}",
    )
    if not args.keep_memory:
        _logger.info(
            "Reset state that remembered the old orders",
            removed=[str(p) for p in reset_derived_state()],
        )
    _logger.info(f"Built eval fixture {EvalFixture().build()}")


if __name__ == "__main__":
    main()
