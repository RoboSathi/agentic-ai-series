"""`make patterns`: which catalogue patterns each agent actually uses, and where.

Reads the decision record (`catalogue.py`) and every registered agent's
`design_docs/patterns.yaml`, and prints one matrix: pattern × agent ×
where it is used × the episode that teaches it. A catalogue pattern no
agent uses is flagged — that list is an input to episode planning, since
a pattern the series teaches but no running product shows is taught in
the abstract. Patterns an agent names that are not in the catalogue (the
LLD and resilience patterns) are listed separately.

The agents are passed in (`--agent csa=customer_support_agent`), so this
module names none of them.
"""

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

import yaml
from pydantic import BaseModel, Field
from rich.console import Console
from rich.table import Table

from design_patterns.catalogue import ALL_PATTERNS

REPO_ROOT = Path(__file__).resolve().parents[1]
PATTERNS_FILE = Path("design_docs") / "patterns.yaml"
_UNUSED = "—"

console = Console()


class PatternUse(BaseModel):
    """One place an agent uses one pattern."""

    pattern: str
    where: str
    notes: str = ""


class AgentPatterns(BaseModel):
    """An agent's `patterns.yaml`."""

    agent: str
    patterns: list[PatternUse] = Field(default_factory=list)
    other: list[PatternUse] = Field(default_factory=list)


class Coverage(BaseModel):
    """The matrix and what it leaves uncovered."""

    agents: list[str]
    rows: list[list[str]]
    unused: list[str]
    unknown: list[str]
    other: list[list[str]]


def load_agent(package: str, root: Path = REPO_ROOT) -> AgentPatterns:
    path = root / "src" / package / PATTERNS_FILE
    return AgentPatterns.model_validate(yaml.safe_load(path.read_text()))


def coverage(agents: dict[str, AgentPatterns]) -> Coverage:
    known = {card.name for card in ALL_PATTERNS}
    rows, unused = [], []
    for card in ALL_PATTERNS:
        cells = [_where(agents[name], card.name) for name in agents]
        rows.append([card.name, card.family, card.depth_episode, *cells])
        if all(cell == _UNUSED for cell in cells):
            unused.append(card.name)
    unknown = [
        f"{name}: {use.pattern}"
        for name, patterns in agents.items()
        for use in patterns.patterns
        if use.pattern not in known
    ]
    other = [[use.pattern, name, use.where] for name, a in agents.items() for use in a.other]
    return Coverage(agents=list(agents), rows=rows, unused=unused, unknown=unknown, other=other)


def _where(agent: AgentPatterns, pattern: str) -> str:
    uses = [use.where for use in agent.patterns if use.pattern == pattern]
    return "; ".join(uses) if uses else _UNUSED


def markdown(result: Coverage) -> str:
    """The same matrix as a Markdown document (`design_docs/patterns_coverage.md`)."""
    header = ["pattern", "family", "taught in", *result.agents]
    lines = [
        "# Pattern coverage",
        "",
        "Generated by `make patterns` from `design_patterns/catalogue.py` and each",
        "agent's `design_docs/patterns.yaml`. Do not edit by hand.",
        "",
        _md_row(header),
        _md_row(["---"] * len(header)),
        *(_md_row(row) for row in result.rows),
        "",
        "## Catalogue patterns no agent uses",
        "",
        *([f"- {name}" for name in result.unused] or ["- none"]),
        "",
        "## Patterns outside the catalogue (LLD, resilience)",
        "",
        _md_row(["pattern", "agent", "where"]),
        _md_row(["---"] * 3),
        *(_md_row(row) for row in result.other),
    ]
    return "\n".join(lines) + "\n"


def _md_row(cells: Sequence[str]) -> str:
    return "| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |"


def _print(result: Coverage) -> None:
    table = Table(title="Pattern coverage")
    for column in ["pattern", "family", "taught in", *result.agents]:
        table.add_column(column, overflow="fold")
    for row in result.rows:
        table.add_row(*row)
    console.print(table)
    console.print(
        f"[yellow]Used by no agent ({len(result.unused)}):[/yellow] "
        f"{', '.join(result.unused) or 'none'}"
    )
    for problem in result.unknown:
        console.print(f"[red]Not a catalogue pattern: {problem}[/red]")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m design_patterns.coverage")
    parser.add_argument("--agent", action="append", default=[], help="name=package")
    parser.add_argument("--markdown", default="", help="also write the matrix here")
    args = parser.parse_args(argv)
    agents = {
        name: load_agent(package) for name, package in (pair.split("=", 1) for pair in args.agent)
    }
    result = coverage(agents)
    _print(result)
    if args.markdown:
        Path(args.markdown).write_text(markdown(result))
    return 1 if result.unknown else 0


if __name__ == "__main__":
    sys.exit(main())
